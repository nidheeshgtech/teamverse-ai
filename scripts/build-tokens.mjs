#!/usr/bin/env node
// Generates src/styles/tokens.css from the Stitch design system (design/DESIGN.md front matter)
// plus the supplementary tokens below that DESIGN.md only describes in prose.
// Re-run after re-exporting from Stitch: `npm run tokens`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(resolve(root, "design/DESIGN.md"), "utf8");
const match = source.match(/^---\n([\s\S]*?)\n---/);
if (!match) throw new Error("design/DESIGN.md has no YAML front matter");
const design = parse(match[1]);

// Values DESIGN.md states in prose ("Elevation & Depth", "Components") rather than front matter.
const supplementary = {
  colors: {
    // Text on the primary emerald button (DESIGN.md › Buttons: "#06090F").
    "on-primary-action": "#06090F",
    "text-strong": "#F8FAFC",
    // Destructive button (DESIGN.md › Buttons).
    "destructive-fill": "rgba(244, 63, 94, 0.12)",
    "destructive-border": "rgba(244, 63, 94, 0.35)",
    "destructive-text": "#FB7185",
    "glass-fill": "rgba(255, 255, 255, 0.05)",
    "glass-fill-hover": "rgba(255, 255, 255, 0.10)",
    "glass-line": "rgba(255, 255, 255, 0.10)",
    "input-fill": "rgba(6, 9, 15, 0.6)",
    // DESIGN GAP: DESIGN.md names department hues (Development: Cyan, Design: Violet,
    // Marketing: Amber, Management: Emerald) without hex values and omits Meeting Room.
    // Hexes below are taken from the Stitch Three.js scene; meeting-room uses secondary teal.
    "dept-development": "#22D3EE",
    "dept-design": "#A78BFA",
    "dept-marketing": "#F59E0B",
    "dept-project-management": "#10B981",
    "dept-meeting-room": "#6BD8CB",
  },
  shadows: {
    "level-1": "0 8px 32px -4px rgba(0, 0, 0, 0.5)",
    "level-2": "inset 0 1px 0 0 rgba(255, 255, 255, 0.12), 0 8px 32px -4px rgba(0, 0, 0, 0.5)",
    "level-3": "0 0 0 1px rgba(16, 185, 129, 0.25), 0 20px 48px -8px rgba(0, 0, 0, 0.8)",
    "topbar": "0 1px 8px rgba(0, 0, 0, 0.3)",
    "glow-primary": "0 0 20px rgba(16, 185, 129, 0.3)",
    "primary-rest": "inset 0 1px 0 0 rgba(255, 255, 255, 0.2)",
    "nav-active": "0 0 16px rgba(16, 185, 129, 0.2)",
    "focus-ring": "0 0 0 2px rgba(16, 185, 129, 0.35)",
  },
  glass: {
    // Opacity raised from the Stitch HTML (0.65/0.85/0.94) so text stays legible over the 3D scene.
    "level-1": { fill: "rgba(13, 19, 31, 0.8)", blur: "16px" },
    "level-2": { fill: "rgba(13, 19, 31, 0.93)", blur: "24px" },
    "level-3": { fill: "rgba(9, 13, 22, 0.97)", blur: "32px" },
  },
  // DESIGN.md › Layout: side panels 380–440px; shell sizes measured from the Stitch HTML.
  layout: {
    "sidebar": "18rem",
    "topbar": "4rem",
    "panel-sm": "23.75rem",
    "panel-lg": "27.5rem",
  },
};

const familyVar = {
  Geist: "var(--font-geist)",
  Inter: "var(--font-inter)",
  "JetBrains Mono": "var(--font-jetbrains-mono)",
};
const fallback = {
  Geist: "ui-sans-serif, system-ui, sans-serif",
  Inter: "ui-sans-serif, system-ui, sans-serif",
  "JetBrains Mono": "ui-monospace, SFMono-Regular, Menlo, monospace",
};

const lines = [];
const out = (s = "") => lines.push(s);

out("/* GENERATED by scripts/build-tokens.mjs from design/DESIGN.md — do not edit by hand. */");
out("");
out(":root {");
for (const [name, value] of Object.entries(design.colors)) out(`  --tv-color-${name}: ${value};`);
for (const [name, value] of Object.entries(supplementary.colors)) out(`  --tv-color-${name}: ${value};`);
for (const [name, { fill, blur }] of Object.entries(supplementary.glass)) {
  out(`  --tv-glass-${name}-fill: ${fill};`);
  out(`  --tv-glass-${name}-blur: ${blur};`);
}
out("}");
out("");

out("@theme inline {");
out("  --color-*: initial;");
out("  --color-transparent: transparent;");
out("  --color-current: currentColor;");
for (const name of [...Object.keys(design.colors), ...Object.keys(supplementary.colors)]) {
  out(`  --color-${name}: var(--tv-color-${name});`);
}
out("");
out("  --font-headline: var(--font-geist), " + fallback.Geist + ";");
out("  --font-body: var(--font-inter), " + fallback.Inter + ";");
out("  --font-mono: var(--font-jetbrains-mono), " + fallback["JetBrains Mono"] + ";");
out("");
out("  --radius-*: initial;");
for (const [name, value] of Object.entries(design.rounded)) {
  out(name === "DEFAULT" ? `  --radius: ${value};` : `  --radius-${name}: ${value};`);
}
out("");
for (const [name, value] of Object.entries(design.spacing)) {
  out(`  --spacing-${name}: ${value};`);
}
for (const [name, value] of Object.entries(supplementary.layout)) out(`  --spacing-${name}: ${value};`);
out("");
out("  --shadow-*: initial;");
for (const [name, value] of Object.entries(supplementary.shadows)) out(`  --shadow-${name}: ${value};`);
out("}");
out("");

// One utility per type style so family, size, leading, tracking and weight travel together.
for (const [name, t] of Object.entries(design.typography)) {
  out(`@utility type-${name} {`);
  out(`  font-family: ${familyVar[t.fontFamily]}, ${fallback[t.fontFamily]};`);
  out(`  font-size: ${t.fontSize};`);
  out(`  line-height: ${t.lineHeight};`);
  out(`  letter-spacing: ${t.letterSpacing};`);
  out(`  font-weight: ${t.fontWeight};`);
  if (t.fontFamily === "JetBrains Mono") out("  font-variant-numeric: tabular-nums;");
  out("}");
}
out("");

for (const name of Object.keys(supplementary.glass)) {
  out(`@utility glass-${name} {`);
  out(`  background-color: var(--tv-glass-${name}-fill);`);
  out(`  backdrop-filter: blur(var(--tv-glass-${name}-blur));`);
  out(`  -webkit-backdrop-filter: blur(var(--tv-glass-${name}-blur));`);
  out("  border: 1px solid var(--tv-color-surface-glass-border);");
  out(`  box-shadow: var(--shadow-${name});`);
  out("}");
}

const target = resolve(root, "src/styles/tokens.css");
writeFileSync(target, lines.join("\n") + "\n");
console.log(`Wrote ${target}`);
